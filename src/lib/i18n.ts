const dicts: Record<Lang, Record<Key, string>> = { tr, en };

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  const d = dicts[lang];
  return (key, vars) => {
    let s = d[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace("{" + k + "}", String(v));
    return s;
  };
}

export const I18nContext = createContext<{ t: T; lang: Lang }>({ t: makeT("tr"), lang: "tr" });
export const useT = () => useContext(I18nContext);

export function formatDuration(seconds: number, t: T, lang: Lang): string {
  const n = (x: number) => Math.round(x).toLocaleString(lang === "tr" ? "tr-TR" : "en-US");
  if (seconds < 1) return t("time.instant");
  if (seconds < 60) return t("time.seconds", { n: n(seconds) });
  if (seconds < 3600) return t("time.minutes", { n: n(seconds / 60) });
  if (seconds < 86400) return t("time.hours", { n: n(seconds / 3600) });
  if (seconds < 31_557_600) return t("time.days", { n: n(seconds / 86400) });
  const years = seconds / 31_557_600;
  if (years < 1000) return t("time.years", { n: n(years) });
  if (years < 1e10) return t("time.centuries");
  return t("time.forever");
}

export function formatDate(ts: number, lang: Lang): string {
  return new Date(ts).toLocaleDateString(lang === "tr" ? "tr-TR" : "en-US", { day: "numeric", month: "short", year: "numeric" });
}
